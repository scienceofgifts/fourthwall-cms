/**
 * Generates a deterministic, high-craft SVG data URI illustration for a product
 * so that preview cards look editorial and complete even when only Fourthwall's
 * relative `data-product-url` is present.
 */
export function buildEditorialSvgDataUri(
  title: string,
  subtitle: string,
  accentHex = '#d4af37',
  bgHex = '#161920'
): string {
  const safeTitle = title
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
  const safeSub = subtitle
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

  const words = safeTitle.split(' ');
  const line1 = words.slice(0, 3).join(' ');
  const line2 = words.slice(3, 7).join(' ');

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 600 600" width="600" height="600">
    <defs>
      <radialGradient id="glow" cx="50%" cy="42%" r="58%">
        <stop offset="0%" stop-color="${accentHex}" stop-opacity="0.24"/>
        <stop offset="100%" stop-color="${bgHex}" stop-opacity="1"/>
      </radialGradient>
    </defs>
    <rect width="600" height="600" fill="${bgHex}"/>
    <rect width="600" height="600" fill="url(#glow)"/>
    <rect x="34" y="34" width="532" height="532" rx="18" fill="none" stroke="${accentHex}" stroke-opacity="0.38" stroke-width="2"/>
    <rect x="46" y="46" width="508" height="508" rx="12" fill="none" stroke="${accentHex}" stroke-opacity="0.16" stroke-width="1"/>
    <circle cx="300" cy="220" r="88" fill="none" stroke="${accentHex}" stroke-width="2.5" stroke-opacity="0.65"/>
    <circle cx="300" cy="220" r="72" fill="none" stroke="${accentHex}" stroke-width="1" stroke-dasharray="6 6" stroke-opacity="0.45"/>
    <path d="M270 220 L300 172 L330 220 L300 268 Z" fill="${accentHex}" fill-opacity="0.22" stroke="${accentHex}" stroke-width="2"/>
    <text x="300" y="370" text-anchor="middle" fill="#FBF9F5" font-family="Georgia, serif" font-size="26" font-weight="bold">${line1}</text>
    <text x="300" y="405" text-anchor="middle" fill="#FBF9F5" font-family="Georgia, serif" font-size="22">${line2}</text>
    <text x="300" y="465" text-anchor="middle" fill="${accentHex}" font-family="sans-serif" font-size="15" font-weight="bold" letter-spacing="3">${safeSub.toUpperCase()}</text>
    <text x="300" y="520" text-anchor="middle" fill="#94A3B8" font-family="sans-serif" font-size="12" letter-spacing="2">SCIENCE OF GIFTS • FOURTHWALL EDITION</text>
  </svg>`;

  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

